/// Generates `lib/src/device_info/vendor_map.dart` from the CSV file.
///
/// Run: dart tool/generate_vendor_map.dart
///
/// Works on Linux, macOS, and Windows.
library;

import 'dart:io';

void main() async {
  final csvFile = File(_joinPath('lib', 'assets', 'mac-vendors-export.csv'));
  if (!csvFile.existsSync()) {
    stderr.writeln('CSV not found at ${csvFile.path}');
    exit(1);
  }

  final content = await csvFile.readAsString();
  final entries = _parseVendorCsv(content);
  await _writeVendorMap(entries);
}

Map<String, List<String>> _parseVendorCsv(String csvContent) {
  // Split on \n; \r is stripped per-field to handle all platform line endings.
  final lines = csvContent.split('\n');
  if (lines.isEmpty) {
    throw const FormatException('CSV is empty');
  }

  final entries = <String, List<String>>{};

  for (var i = 1; i < lines.length; i++) {
    final row = _parseCsvLine(lines[i].trimRight());
    if (row.length < 2) continue;
    final prefix = row[0].replaceAll(RegExp('[^0-9a-fA-F]'), '').toUpperCase();
    if (prefix.length != 6) continue;
    final vendorName = row[1].trim();
    if (vendorName.isEmpty) continue;

    final private = row.length > 2 ? row[2].trim() : '';
    final blockType = row.length > 3 ? row[3].trim() : '';
    final lastUpdate = row.length > 4 ? row[4].trim() : '';

    entries[prefix] = [vendorName, private, blockType, lastUpdate];
  }
  return entries;
}

Future<void> _writeVendorMap(Map<String, List<String>> entries) async {
  final sortedKeys = entries.keys.toList()..sort();

  final buf = StringBuffer();
  buf.writeln('// GENERATED FILE — DO NOT EDIT DIRECTLY');
  buf.writeln(
    '// Generated by tool/generate_vendor_map.dart '
    'from lib/assets/mac-vendors-export.csv',
  );
  buf.writeln('// ${sortedKeys.length} MAC vendor entries');
  buf.writeln();
  buf.writeln(
    'const Map<String, (String, String, String, String)> kVendorMap = {',
  );

  for (final key in sortedKeys) {
    final v = entries[key]!;
    buf.writeln(
      "  '$key': (${_dartStr(v[0])}, ${_dartStr(v[1])}, "
      '${_dartStr(v[2])}, ${_dartStr(v[3])}),',
    );
  }

  buf.writeln('};');

  final outFile = File(
    _joinPath('lib', 'src', 'device_info', 'vendor_map.dart'),
  );
  await outFile.writeAsString(buf.toString());
  stdout.writeln('Generated ${outFile.path} with ${sortedKeys.length} entries');
}

/// Cross-platform path join using Platform.pathSeparator.
String _joinPath(
  String part1,
  String part2, [
  String? part3,
  String? part4,
  String? part5,
]) {
  final parts = [part1, part2, ?part3, ?part4, ?part5];
  return parts.join(Platform.pathSeparator);
}

/// Returns a Dart string literal, choosing single or double quotes to
/// minimise escaping.
String _dartStr(String s) {
  if (s.isEmpty) return "''";
  final hasSingle = s.contains("'");
  final hasDouble = s.contains('"');
  final hasDollar = s.contains(r'$');
  final hasBackslash = s.contains(r'\');

  if (!hasSingle) {
    // Use single quotes — no escaping needed for ' or ".
    var out = s;
    if (hasBackslash) out = out.replaceAll(r'\', r'\\');
    if (hasDollar) out = out.replaceAll(r'$', r'\$');
    return "'$out'";
  }

  if (!hasDouble) {
    // Use double quotes to avoid escaping single quotes.
    var out = s;
    if (hasBackslash) out = out.replaceAll(r'\', r'\\');
    if (hasDollar) out = out.replaceAll(r'$', r'\$');
    return '"$out"';
  }

  // Both ' and " present — use single quotes and escape '.
  var out = s;
  if (hasBackslash) out = out.replaceAll(r'\', r'\\');
  if (hasDollar) out = out.replaceAll(r'$', r'\$');
  out = out.replaceAll("'", r"\'");
  return "'$out'";
}

List<String> _parseCsvLine(String line) {
  final fields = <String>[];
  final buf = StringBuffer();
  var inQuotes = false;

  for (var i = 0; i < line.length; i++) {
    final ch = line[i];
    if (inQuotes) {
      if (ch == '"') {
        if (i + 1 < line.length && line[i + 1] == '"') {
          buf.write('"');
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        buf.write(ch);
      }
    } else {
      if (ch == '"') {
        inQuotes = true;
      } else if (ch == ',') {
        fields.add(buf.toString());
        buf.clear();
      } else {
        buf.write(ch);
      }
    }
  }
  fields.add(buf.toString());
  return fields;
}
