import 'dart:convert';
import 'dart:io';

import 'package:hooks/hooks.dart';

/// Downloads the MAC vendor CSV at compile time and generates a Dart const map
/// so consuming apps get vendor lookups without any runtime network dependency.
///
/// Works on Linux, macOS, and Windows. File paths use URI resolution via
/// [HookInput.packageRoot] which handles platform separators correctly.
///
/// The generated file is written to the package's `lib/src/device_info/`
/// directory. The CSV itself is excluded from the published package via
/// `.pubignore`, so this hook is the mechanism that makes vendor data
/// available to consumers.
void main(List<String> args) async {
  await build(args, (input, output) async {
    final packageName = input.packageName;
    const fileName = 'mac-vendors-export.csv';
    const downloadUrl =
        'https://raw.githubusercontent.com/osociety/network_tools/'
        'main/lib/assets/mac-vendors-export.csv';
    const timeout = Duration(seconds: 30);

    // URI resolution is cross-platform — input.packageRoot uses forward
    // slashes in its URI representation regardless of OS.
    final bundledCsv = input.packageRoot.resolve('lib/assets/$fileName');
    final bundledFile = File.fromUri(bundledCsv);

    String? csvContent;

    // Prefer the bundled CSV (available in the source repo and in the pub
    // cache when the file is not excluded by .pubignore).
    if (bundledFile.existsSync()) {
      csvContent = bundledFile.readAsStringSync();
    }

    // Fall back to downloading when the bundled file is missing (e.g. the
    // CSV is excluded from the published package via .pubignore).
    if (csvContent == null) {
      try {
        final client = HttpClient()..connectionTimeout = timeout;
        final request = await client.getUrl(Uri.parse(downloadUrl));
        final response = await request.close().timeout(timeout);

        if (response.statusCode == 200) {
          final chunks = <String>[];
          await response.transform(utf8.decoder).forEach(chunks.add);
          csvContent = chunks.join();
        } else {
          stderr.writeln(
            '[$packageName] Vendor table download returned '
            '${response.statusCode}',
          );
        }
        client.close();
      } catch (e) {
        stderr.writeln('[$packageName] Vendor table download failed: $e');
      }
    }

    if (csvContent != null) {
      final generated = _generateVendorMap(csvContent);
      final outFile = File.fromUri(
        input.packageRoot.resolve('lib/src/device_info/vendor_map.dart'),
      );
      await outFile.writeAsString(generated);
    }
  });
}

String _generateVendorMap(String csvContent) {
  // Split on \n; \r is stripped per-field to handle all platform line endings.
  final lines = csvContent.split('\n');
  final entries = <String, List<String>>{};

  for (var i = 1; i < lines.length; i++) {
    final row = _parseCsvLine(lines[i].trimRight());
    if (row.length < 2) continue;
    final prefix = row[0].replaceAll(RegExp('[^0-9a-fA-F]'), '').toUpperCase();
    if (prefix.length != 6) continue;
    final vendorName = row[1].trim();
    if (vendorName.isEmpty) continue;

    final private = row.length > 2 ? row[2].trim() : '';
    final blockType = row.length > 3 ? row[3].trim() : '';
    final lastUpdate = row.length > 4 ? row[4].trim() : '';

    entries[prefix] = [vendorName, private, blockType, lastUpdate];
  }

  final sortedKeys = entries.keys.toList()..sort();

  final buf = StringBuffer();
  buf.writeln('// GENERATED FILE — DO NOT EDIT DIRECTLY');
  buf.writeln(
    '// Generated by hook/build.dart — '
    'downloads MAC vendor CSV at compile time',
  );
  buf.writeln('// ${sortedKeys.length} MAC vendor entries');
  buf.writeln();
  buf.writeln(
    'const Map<String, (String, String, String, String)> kVendorMap = {',
  );

  for (final key in sortedKeys) {
    final v = entries[key]!;
    buf.writeln(
      "  '$key': (${_dartStr(v[0])}, ${_dartStr(v[1])}, "
      '${_dartStr(v[2])}, ${_dartStr(v[3])}),',
    );
  }

  buf.writeln('};');
  return buf.toString();
}

/// Returns a Dart string literal, choosing single or double quotes to
/// minimise escaping.
String _dartStr(String s) {
  if (s.isEmpty) return "''";
  final hasSingle = s.contains("'");
  final hasDouble = s.contains('"');
  final hasDollar = s.contains(r'$');
  final hasBackslash = s.contains(r'\');

  if (!hasSingle) {
    var out = s;
    if (hasBackslash) out = out.replaceAll(r'\', r'\\');
    if (hasDollar) out = out.replaceAll(r'$', r'\$');
    return "'$out'";
  }

  if (!hasDouble) {
    var out = s;
    if (hasBackslash) out = out.replaceAll(r'\', r'\\');
    if (hasDollar) out = out.replaceAll(r'$', r'\$');
    return '"$out"';
  }

  var out = s;
  if (hasBackslash) out = out.replaceAll(r'\', r'\\');
  if (hasDollar) out = out.replaceAll(r'$', r'\$');
  out = out.replaceAll("'", r"\'");
  return "'$out'";
}

List<String> _parseCsvLine(String line) {
  final fields = <String>[];
  final buf = StringBuffer();
  var inQuotes = false;

  for (var i = 0; i < line.length; i++) {
    final ch = line[i];
    if (inQuotes) {
      if (ch == '"') {
        if (i + 1 < line.length && line[i + 1] == '"') {
          buf.write('"');
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        buf.write(ch);
      }
    } else {
      if (ch == '"') {
        inQuotes = true;
      } else if (ch == ',') {
        fields.add(buf.toString());
        buf.clear();
      } else {
        buf.write(ch);
      }
    }
  }
  fields.add(buf.toString());
  return fields;
}
